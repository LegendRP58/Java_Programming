    private void CountButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CountButtonActionPerformed
    int selectedRow = TableModel.getSelectedRow(); 
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Выберите строку для вычисления", "Информация", JOptionPane.WARNING_MESSAGE);
        return; 
    }
    try{
        DefaultTableModel model = (DefaultTableModel) TableModel.getModel();
        double step = Double.parseDouble( TableModel.getValueAt(selectedRow, 0).toString());
        double lowlim = Double.parseDouble( TableModel.getValueAt(selectedRow, 1).toString());
        double uplim = Double.parseDouble( TableModel.getValueAt(selectedRow, 2).toString());
        double result = computeIntegral(step, lowlim,uplim);

        // Форматируем результат до 5 знаков
        String formattedResult = String.format("%.5f", result);
        model.setValueAt(formattedResult, selectedRow, 3);
    }
    catch(Exception e){
         JOptionPane.showMessageDialog(this, "Ошибка при вычислении: " + e.getMessage(), "Ошибка", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_CountButtonActionPerformed

