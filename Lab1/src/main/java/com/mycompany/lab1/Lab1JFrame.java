    private void AddToTableButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddToTableButtonActionPerformed
        try {
            double step = Double.parseDouble(StepTextField.getText());
            double lowlim = Double.parseDouble(LowerLimitTextField.getText());
            double uplim = Double.parseDouble(UpperLimitTextField.getText());
            
             // Проверка корректности: lowlim < uplim, step > 0 и т.д.
        if (lowlim >= uplim || step <= 0) {
            JOptionPane.showMessageDialog(this, "Некорректные параметры: lowlim < uplim, step > 0", "Ошибка", JOptionPane.ERROR_MESSAGE);
            return;
        }
         // получаем модель и добавляем строку
        DefaultTableModel model = (DefaultTableModel) TableModel.getModel();
        model.addRow(new Object[]{step, lowlim, uplim, ""});
        }
        catch (NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Введите корректные числа", "Ошибка", JOptionPane.ERROR_MESSAGE);
        };
    }//GEN-LAST:event_AddToTableButtonActionPerformed

